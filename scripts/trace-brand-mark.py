#!/usr/bin/env python3
"""Trace the owner's app-icon artwork into SVG path data.

The dark app-icon tile supplied in October 2026 (a "K" drawn as a gold truss
with white rivets and a green leaf) is flat colour on a flat ground, so it can
be vectorised cleanly instead of hand-redrawn. This script:

  1. finds the tile in the supplied JPEG,
  2. splits it into the four colours it actually uses,
  3. traces each colour layer with potrace,
  4. prints JavaScript that src/components/brandMarkArt.js can hold.

Run it only when the artwork changes:

    python3 scripts/trace-brand-mark.py uploads/icon.jpeg

Needs potrace on PATH and Pillow (`pip install pillow`).
"""
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image, ImageFilter

SIZE = 1024          # working resolution; output is normalised to 512
OUT_VIEWBOX = 512

# Colours measured from the supplied image.
GROUND = (23, 46, 30)     # #172E1E dark green tile
GOLD = (200, 160, 74)     # the truss
GREEN = (47, 120, 69)     # the leaf and its stalk
CREAM = (242, 240, 228)   # the rivets


def nearest(ref, colours):
    return min(colours, key=lambda c: sum((a - b) ** 2 for a, b in zip(ref, c)))


def find_tile(im):
    """The tile's edges, found from how much dark ground each row and column holds.

    A plain bounding box of dark pixels is wrong: the drop shadow and the black
    caption lettering match the ground colour too. Inside the tile almost every
    pixel of a row is ground or artwork, so rows and columns that are mostly
    ground give the four edges exactly. Only the left half of the sheet is
    searched, because the light variation on the right uses the same dark ink.
    """
    px = im.load()
    w, h = im.size
    half = w // 2

    def ground(x, y):
        r, g, b = px[x, y]
        return abs(r - GROUND[0]) + abs(g - GROUND[1]) + abs(b - GROUND[2]) < 45

    rows = [sum(1 for x in range(half) if ground(x, y)) for y in range(h)]
    cols = [sum(1 for y in range(h) if ground(x, y)) for x in range(half)]
    row_edges = [i for i, c in enumerate(rows) if c > 150]
    col_edges = [i for i, c in enumerate(cols) if c > 150]
    assert row_edges and col_edges, "could not find the dark tile"
    return col_edges[0], row_edges[0], col_edges[-1], row_edges[-1]


def trace(mask, out_svg):
    """potrace one 1-bit mask; returns the path data with potrace's transform folded in."""
    # potrace fills BLACK areas, so the shape must be black, and the mask has to
    # be thresholded without dithering.
    binary = mask.point(lambda v: 0 if v > 128 else 255).convert("1", dither=Image.NONE)
    with tempfile.NamedTemporaryFile(suffix=".pbm", delete=False) as f:
        binary.save(f.name)
        pbm = f.name
    subprocess.run(
        ["potrace", pbm, "-s", "-o", out_svg, "--turdsize", "40",
         "--alphamax", "1.0", "--opttolerance", "0.3"],
        check=True,
    )
    svg = Path(out_svg).read_text()
    # potrace writes one <path d="..."/> per layer after a translate/scale group.
    paths = []
    for chunk in svg.split('d="')[1:]:
        paths.append(chunk.split('"')[0])
    return paths


def main():
    src = Path(sys.argv[1] if len(sys.argv) > 1 else "uploads/icon.jpeg")
    im = Image.open(src).convert("RGB")
    box = find_tile(im)
    print("tile box:", box, file=sys.stderr)
    tile = im.crop((box[0], box[1], box[2] + 1, box[3] + 1)).resize((SIZE, SIZE), Image.LANCZOS)
    tile = tile.filter(ImageFilter.GaussianBlur(1.2))

    colours = [GROUND, GOLD, GREEN, CREAM]
    labels = {GROUND: "ground", GOLD: "gold", GREEN: "green", CREAM: "cream"}
    layers = {c: Image.new("L", (SIZE, SIZE), 0) for c in colours}
    px = tile.load()
    for y in range(SIZE):
        for x in range(SIZE):
            layers[nearest(px[x, y], colours)].putpixel((x, y), 255)

    out = {}
    with tempfile.TemporaryDirectory() as tmp:
        for colour in (GOLD, GREEN, CREAM):
            mask = layers[colour].filter(ImageFilter.MedianFilter(5))
            paths = trace(mask, f"{tmp}/{labels[colour]}.svg")
            out[labels[colour]] = paths
            print(f"{labels[colour]}: {len(paths)} path(s)", file=sys.stderr)

    # potrace emits coordinates in 1/10 px with y flipped; fold that into a
    # single transform that maps the 1024 working canvas onto the 512 viewBox.
    scale = OUT_VIEWBOX / SIZE * 0.1
    transform = f"translate(0,{OUT_VIEWBOX}) scale({scale:.6f},-{scale:.6f})"

    print("// Generated by scripts/trace-brand-mark.py from the supplied app icon.")
    print(f'export const MARK_TRANSFORM = "{transform}";')
    for name, paths in out.items():
        joined = " ".join(paths)
        print(f'export const MARK_{name.upper()}_PATHS = "{joined}";')


if __name__ == "__main__":
    main()
